import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import fetch from "node-fetch";
import { HttpsProxyAgent } from "https-proxy-agent";

const apiUrl =
  "https://api.bsdd.buildingsmart.org/api/Dictionary/v1/Classes";
const dictionaryUri =
  "https://identifier.buildingsmart.org/uri/buildingsmart/ifc/4.3";
const pageSize = 500;
const outputPath = path.resolve("src/constants/IfcClasses.ts");
const proxyUrl = process.env.HTTPS_PROXY ?? process.env.HTTP_PROXY;
const fetchOptions = proxyUrl
  ? { agent: new HttpsProxyAgent(proxyUrl) }
  : undefined;

const classes = [];

for (let offset = 0; ; offset += pageSize) {
  const params = new URLSearchParams({
    Uri: dictionaryUri,
    ClassType: "Class",
    Offset: String(offset),
    Limit: String(pageSize),
  });
  const response = await fetch(`${apiUrl}?${params}`, fetchOptions);
  if (!response.ok) {
    throw new Error(`bSDD request failed with status ${response.status}`);
  }

  const payload = await response.json();
  const page = Array.isArray(payload.classes) ? payload.classes : [];
  classes.push(
    ...page.map(({ code, uri }) => ({ code, uri })),
  );

  console.log(`Loaded ${classes.length} classes`);
  if (page.length < pageSize) break;
}

const uniqueClasses = Array.from(
  new Map(classes.map((item) => [item.uri, item])).values(),
);
const file = `// Generated by scripts/fetch-ifc-classes.mjs. Do not edit manually.
export type IfcClass = {
  code: string;
  uri: string;
};

export const ifcClasses: IfcClass[] = ${JSON.stringify(uniqueClasses, null, 2)};
`;

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, file, "utf8");
console.log(`Wrote ${uniqueClasses.length} classes to ${outputPath}`);
